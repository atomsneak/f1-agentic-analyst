#!/usr/bin/env python3
"""PWA wiring tests -- no server, no database, no network.

What is worth asserting here is exactly what breaks installability, and every
one of these has a silent failure mode: a missing icon 404s only in DevTools, a
manifest with an absolute `start_url` installs fine and then opens the wrong
surface from the wrong URL, and a service worker outside the page's
directory registers successfully with a scope that controls nothing.

So the tests check:
  1. every precached path maps to a file that exists AND is served by a route;
  2. `start_url` / icon `src` are relative (so a path prefix cannot break them);
  3. every surface's manifest has the fields Chrome's install criteria needs;
  4. the substituted `sw.js` is valid JavaScript and bypasses SSE + writes;
  5. each page's <head> actually links the manifest and its own title.
"""
import json
import os
import re
import subprocess
import sys
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(HERE))

import pwa  # noqa: E402


class TestPrecache(unittest.TestCase):
    #: Generated by a route on each surface rather than stored as a file:
    #: "./" is the page itself, the manifest is built per surface in pwa.py.
    ROUTE_SERVED = {"./", "manifest.webmanifest"}

    def test_every_precached_file_exists(self):
        for rel in pwa.PRECACHE:
            if rel in self.ROUTE_SERVED:
                continue
            self.assertTrue((HERE / rel).is_file(), f"precache'te olmayan dosya: {rel}")

    def test_manifest_is_precached_but_worker_is_not(self):
        # The worker must never cache itself: a worker served from a cache it
        # controls cannot be updated.
        self.assertIn("manifest.webmanifest", pwa.PRECACHE)
        self.assertNotIn("sw.js", pwa.PRECACHE)


class TestManifest(unittest.TestCase):
    def test_all_surfaces(self):
        """Every surface is installable AND has a page that actually serves it.

        `welcome` joined the set when the weekend grid became the landing page.
        The pairing assertion is here because a manifest with no page behind it
        installs fine and then opens a 404 -- an installed broken shortcut is
        worse than no shortcut.
        """
        self.assertEqual(set(pwa.SURFACES), {"live", "archive", "standings", "welcome"})
        pages = {"live": "index.html", "archive": "archive.html",
                 "standings": "standings.html", "welcome": "welcome.html"}
        for name in pwa.SURFACES:
            self.assertTrue((HERE / pages[name]).is_file(), f"{name}: {pages[name]} yok")

    def test_install_criteria(self):
        for name in pwa.SURFACES:
            m = pwa.manifest(name)
            for field in ("name", "short_name", "start_url", "display", "icons",
                          "theme_color", "background_color"):
                self.assertIn(field, m, f"{name}: {field} yok")
            self.assertEqual(m["display"], "standalone")
            sizes = {i["sizes"] for i in m["icons"]}
            self.assertIn("192x192", sizes, name)
            self.assertIn("512x512", sizes, name)
            purposes = {i.get("purpose") for i in m["icons"]}
            self.assertIn("maskable", purposes, name)

    def test_start_url_and_icons_are_relative(self):
        """A manifest served from a sub-path must stay inside that sub-path.

        An absolute `/` start_url would launch the live surface from the archive
        icon if the app is ever mounted under a prefix; an absolute
        `/static/...` icon would 404 there. This build serves every surface at
        the root of its own port, so the check guards a future deployment rather
        than today's -- which is cheap and catches a real regression.
        """
        for name in pwa.SURFACES:
            m = pwa.manifest(name)
            self.assertFalse(m["start_url"].startswith("/"), name)
            self.assertEqual(m["start_url"], "./", name)
            for icon in m["icons"]:
                self.assertFalse(icon["src"].startswith("/"), f"{name}: {icon['src']}")

    def test_manifest_is_json_serialisable(self):
        json.dumps(pwa.manifest("live"))

    def test_unknown_surface_rejected(self):
        class Dummy:
            get = staticmethod(lambda *a, **k: (lambda f: f))
        with self.assertRaises(ValueError):
            pwa.install(Dummy(), "nope")


class TestServiceWorker(unittest.TestCase):
    def setUp(self):
        self.js = pwa.service_worker()

    def test_placeholders_substituted(self):
        self.assertNotIn("%PRECACHE%", self.js)
        self.assertNotIn("%CACHE_VERSION%", self.js)
        self.assertIn(pwa._content_version(), self.js)
        self.assertIn(json.dumps(list(pwa.PRECACHE)), self.js)

    def test_cache_name_changes_when_a_cached_file_changes(self):
        """The cache name must be derived, not typed.

        It used to be the constant "f1-shell-v1" with a comment saying "bump when
        a precached asset changes". Nobody bumped it, the worker's own bytes never
        changed, the browser never reinstalled it, and an edit to the page and to
        shell.js was invisible to a returning user -- reported as "değişiklik yok
        gibi". A derived name cannot be forgotten.
        """
        base = pwa._content_version("live")
        self.assertRegex(base, r"^f1-shell-[0-9a-f]{12}$")
        # Different surface pages must give different names, or two installed
        # apps would share one cache and evict each other.
        self.assertNotEqual(base, pwa._content_version("archive"))
        self.assertNotEqual(base, pwa._content_version("welcome"))

    def test_cache_name_is_stable_for_unchanged_files(self):
        # Same inputs twice: an unstable name would evict the cache on every
        # page load and destroy the offline guarantee.
        self.assertEqual(pwa._content_version("live"), pwa._content_version("live"))

    def test_valid_javascript(self):
        node = subprocess.run(["node", "--version"], capture_output=True)
        if node.returncode != 0:
            self.skipTest("node yok")
        import tempfile
        with tempfile.NamedTemporaryFile("w", suffix=".js", delete=False) as f:
            f.write(self.js)
            path = f.name
        try:
            r = subprocess.run(["node", "--check", path], capture_output=True, text=True)
            self.assertEqual(r.returncode, 0, r.stderr[:500])
        finally:
            os.unlink(path)

    def test_stream_and_writes_bypassed(self):
        # Guard the two decisions that break the app if removed: caching a
        # never-ending SSE response, and pretending a POST succeeded.
        self.assertIn('if (req.method !== "GET") return;', self.js)
        self.assertIn("isStream(url)", self.js)
        self.assertIn('endsWith("/api/stream")', self.js)

    def test_old_caches_evicted(self):
        self.assertIn("caches.delete(n)", self.js)


class TestPages(unittest.TestCase):
    PAGES = {
        "index.html": "F1 Canlı",
        "archive.html": "F1 Arşiv",
        "standings.html": "F1 Puan",
    }

    def test_head_tags(self):
        for page, title in self.PAGES.items():
            src = (HERE / page).read_text(encoding="utf-8")
            head = src.split("</head>", 1)[0]
            self.assertIn('<link rel="manifest" href="manifest.webmanifest">', head, page)
            self.assertIn('name="theme-color"', head, page)
            self.assertIn('href="static/icons/apple-touch-icon-180.png"', head, page)
            self.assertIn(f'content="{title}"', head, page)
            # Relative, so a path prefix cannot break the manifest link.
            self.assertNotIn('href="/manifest', head, page)

    def test_theme_colour_matches_background_token(self):
        css = (HERE / "static" / "theme.css").read_text(encoding="utf-8")
        m = re.search(r"--bg:\s*([#0-9a-fA-F]+)", css)
        self.assertIsNotNone(m)
        self.assertEqual(m.group(1).lower(), pwa.THEME_COLOR.lower(),
                         "manifest theme_color ile --bg ayrışmış: kurulu uygulama beyaz flaş verir")


class TestShellJS(unittest.TestCase):
    def test_registers_relative_worker(self):
        src = (HERE / "static" / "shell.js").read_text(encoding="utf-8")
        self.assertIn('navigator.serviceWorker.register("sw.js")', src)
        self.assertIn("isSecureContext", src)
        self.assertIn("netbadge", src)


if __name__ == "__main__":
    unittest.main()
